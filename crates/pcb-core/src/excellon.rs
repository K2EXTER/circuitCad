//! Excellon drill file writer (metric, decimal coordinates).

use crate::model::*;
use std::fmt::Write;

fn key(d: f64) -> i64 {
    (d * 1000.0).round() as i64 // 1 µm
}

fn write_file(function: &str, hits: &[(f64, Point)]) -> String {
    let mut tools: Vec<i64> = hits.iter().map(|h| key(h.0)).collect();
    tools.sort_unstable();
    tools.dedup();

    let mut s = String::new();
    s.push_str("M48\n");
    let _ = writeln!(s, "; DRILL file generated by circuitCad");
    let _ = writeln!(s, "; FORMAT=absolute / metric / decimal");
    let _ = writeln!(s, "; #@! TF.GenerationSoftware,circuitCad,pcb-core,0.1");
    let _ = writeln!(s, "; #@! TF.FileFunction,{function}");
    s.push_str("FMAT,2\nMETRIC\n");
    for (i, t) in tools.iter().enumerate() {
        let _ = writeln!(s, "T{}C{:.3}", i + 1, *t as f64 / 1000.0);
    }
    s.push_str("%\nG90\nG05\n");
    for (i, t) in tools.iter().enumerate() {
        let _ = writeln!(s, "T{}", i + 1);
        for (d, p) in hits.iter().filter(|h| key(h.0) == *t) {
            let _ = d;
            let _ = writeln!(s, "X{:.4}Y{:.4}", p.x, p.y);
        }
    }
    s.push_str("T0\nM30\n");
    s
}

/// Plated holes: through-hole pad drills and vias.
pub fn plated(board: &Board) -> String {
    let mut hits = vec![];
    for p in &board.pads {
        if let Some(d) = p.drill {
            hits.push((d, p.pos));
        }
    }
    for v in &board.vias {
        hits.push((v.drill, v.pos));
    }
    write_file("Plated,1,2,PTH", &hits)
}

pub fn non_plated(board: &Board) -> String {
    let hits: Vec<_> = board.holes.iter().map(|h| (h.drill, h.pos)).collect();
    write_file("NonPlated,1,2,NPTH", &hits)
}

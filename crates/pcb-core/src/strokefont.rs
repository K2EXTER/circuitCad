//! A minimal single-stroke font for silkscreen text (digits, capitals and a few symbols).
//! Glyphs live on a 4 x 6 grid; lower case is shown as upper case.

use crate::model::Point;

type Glyph = &'static [&'static [(f32, f32)]];

const OCT: &[(f32, f32)] = &[(1.0, 0.0), (3.0, 0.0), (4.0, 1.0), (4.0, 5.0), (3.0, 6.0), (1.0, 6.0), (0.0, 5.0), (0.0, 1.0), (1.0, 0.0)];

fn glyph(c: char) -> Glyph {
    match c.to_ascii_uppercase() {
        '0' | 'O' => &[OCT],
        '1' => &[&[(1.0, 5.0), (2.0, 6.0), (2.0, 0.0)], &[(1.0, 0.0), (3.0, 0.0)]],
        '2' => &[&[(0.0, 5.0), (1.0, 6.0), (3.0, 6.0), (4.0, 5.0), (4.0, 4.0), (0.0, 0.0), (4.0, 0.0)]],
        '3' => &[
            &[(0.0, 5.0), (1.0, 6.0), (3.0, 6.0), (4.0, 5.0), (4.0, 4.0), (3.0, 3.0), (1.0, 3.0)],
            &[(3.0, 3.0), (4.0, 2.0), (4.0, 1.0), (3.0, 0.0), (1.0, 0.0), (0.0, 1.0)],
        ],
        '4' => &[&[(3.0, 0.0), (3.0, 6.0), (0.0, 2.0), (4.0, 2.0)]],
        '5' => &[&[(4.0, 6.0), (0.0, 6.0), (0.0, 3.0), (3.0, 3.0), (4.0, 2.0), (4.0, 1.0), (3.0, 0.0), (0.0, 0.0)]],
        '6' => &[&[(4.0, 5.0), (3.0, 6.0), (1.0, 6.0), (0.0, 5.0), (0.0, 1.0), (1.0, 0.0), (3.0, 0.0), (4.0, 1.0), (4.0, 2.0), (3.0, 3.0), (0.0, 3.0)]],
        '7' => &[&[(0.0, 6.0), (4.0, 6.0), (1.0, 0.0)]],
        '8' => &[&[
            (1.0, 3.0), (0.0, 4.0), (0.0, 5.0), (1.0, 6.0), (3.0, 6.0), (4.0, 5.0), (4.0, 4.0), (3.0, 3.0), (1.0, 3.0),
            (0.0, 2.0), (0.0, 1.0), (1.0, 0.0), (3.0, 0.0), (4.0, 1.0), (4.0, 2.0), (3.0, 3.0),
        ]],
        '9' => &[&[(0.0, 1.0), (1.0, 0.0), (3.0, 0.0), (4.0, 1.0), (4.0, 5.0), (3.0, 6.0), (1.0, 6.0), (0.0, 5.0), (0.0, 4.0), (1.0, 3.0), (4.0, 3.0)]],
        'A' => &[&[(0.0, 0.0), (2.0, 6.0), (4.0, 0.0)], &[(1.0, 2.0), (3.0, 2.0)]],
        'B' => &[
            &[(0.0, 0.0), (0.0, 6.0), (3.0, 6.0), (4.0, 5.0), (4.0, 4.0), (3.0, 3.0), (0.0, 3.0)],
            &[(3.0, 3.0), (4.0, 2.0), (4.0, 1.0), (3.0, 0.0), (0.0, 0.0)],
        ],
        'C' => &[&[(4.0, 5.0), (3.0, 6.0), (1.0, 6.0), (0.0, 5.0), (0.0, 1.0), (1.0, 0.0), (3.0, 0.0), (4.0, 1.0)]],
        'D' => &[&[(0.0, 0.0), (0.0, 6.0), (2.0, 6.0), (4.0, 4.0), (4.0, 2.0), (2.0, 0.0), (0.0, 0.0)]],
        'E' => &[&[(4.0, 6.0), (0.0, 6.0), (0.0, 0.0), (4.0, 0.0)], &[(0.0, 3.0), (3.0, 3.0)]],
        'F' => &[&[(4.0, 6.0), (0.0, 6.0), (0.0, 0.0)], &[(0.0, 3.0), (3.0, 3.0)]],
        'G' => &[&[(4.0, 5.0), (3.0, 6.0), (1.0, 6.0), (0.0, 5.0), (0.0, 1.0), (1.0, 0.0), (3.0, 0.0), (4.0, 1.0), (4.0, 3.0), (2.0, 3.0)]],
        'H' => &[&[(0.0, 0.0), (0.0, 6.0)], &[(4.0, 0.0), (4.0, 6.0)], &[(0.0, 3.0), (4.0, 3.0)]],
        'I' => &[&[(1.0, 6.0), (3.0, 6.0)], &[(2.0, 6.0), (2.0, 0.0)], &[(1.0, 0.0), (3.0, 0.0)]],
        'J' => &[&[(4.0, 6.0), (4.0, 1.0), (3.0, 0.0), (1.0, 0.0), (0.0, 1.0)]],
        'K' => &[&[(0.0, 0.0), (0.0, 6.0)], &[(4.0, 6.0), (0.0, 3.0), (4.0, 0.0)]],
        'L' => &[&[(0.0, 6.0), (0.0, 0.0), (4.0, 0.0)]],
        'M' => &[&[(0.0, 0.0), (0.0, 6.0), (2.0, 3.0), (4.0, 6.0), (4.0, 0.0)]],
        'N' => &[&[(0.0, 0.0), (0.0, 6.0), (4.0, 0.0), (4.0, 6.0)]],
        'P' => &[&[(0.0, 0.0), (0.0, 6.0), (3.0, 6.0), (4.0, 5.0), (4.0, 4.0), (3.0, 3.0), (0.0, 3.0)]],
        'Q' => &[OCT, &[(2.0, 2.0), (4.0, 0.0)]],
        'R' => &[&[(0.0, 0.0), (0.0, 6.0), (3.0, 6.0), (4.0, 5.0), (4.0, 4.0), (3.0, 3.0), (0.0, 3.0)], &[(2.0, 3.0), (4.0, 0.0)]],
        'S' => &[&[(4.0, 5.0), (3.0, 6.0), (1.0, 6.0), (0.0, 5.0), (0.0, 4.0), (1.0, 3.0), (3.0, 3.0), (4.0, 2.0), (4.0, 1.0), (3.0, 0.0), (1.0, 0.0), (0.0, 1.0)]],
        'T' => &[&[(0.0, 6.0), (4.0, 6.0)], &[(2.0, 6.0), (2.0, 0.0)]],
        'U' => &[&[(0.0, 6.0), (0.0, 1.0), (1.0, 0.0), (3.0, 0.0), (4.0, 1.0), (4.0, 6.0)]],
        'V' => &[&[(0.0, 6.0), (2.0, 0.0), (4.0, 6.0)]],
        'W' => &[&[(0.0, 6.0), (1.0, 0.0), (2.0, 3.0), (3.0, 0.0), (4.0, 6.0)]],
        'X' => &[&[(0.0, 6.0), (4.0, 0.0)], &[(0.0, 0.0), (4.0, 6.0)]],
        'Y' => &[&[(0.0, 6.0), (2.0, 3.0), (4.0, 6.0)], &[(2.0, 3.0), (2.0, 0.0)]],
        'Z' => &[&[(0.0, 6.0), (4.0, 6.0), (0.0, 0.0), (4.0, 0.0)]],
        '-' => &[&[(1.0, 3.0), (3.0, 3.0)]],
        '+' => &[&[(1.0, 3.0), (3.0, 3.0)], &[(2.0, 2.0), (2.0, 4.0)]],
        '.' => &[&[(2.0, 0.0), (2.0, 0.5)]],
        '/' => &[&[(0.0, 0.0), (4.0, 6.0)]],
        '_' => &[&[(0.0, 0.0), (4.0, 0.0)]],
        '=' => &[&[(1.0, 2.0), (3.0, 2.0)], &[(1.0, 4.0), (3.0, 4.0)]],
        '(' => &[&[(3.0, 6.0), (2.0, 5.0), (2.0, 1.0), (3.0, 0.0)]],
        ')' => &[&[(1.0, 6.0), (2.0, 5.0), (2.0, 1.0), (1.0, 0.0)]],
        ' ' => &[],
        _ => &[&[(0.0, 5.0), (1.0, 6.0), (3.0, 6.0), (4.0, 5.0), (4.0, 4.0), (2.0, 3.0), (2.0, 2.0)], &[(2.0, 0.0), (2.0, 0.5)]],
    }
}

/// Width of `text` for a given character height.
pub fn text_width(text: &str, height: f64) -> f64 {
    let n = text.chars().count() as f64;
    if n == 0.0 { 0.0 } else { (n * 6.0 - 2.0) * height / 6.0 }
}

/// Line segments of `text`, centred on the origin, `height` mm tall. `mirror` flips x (text on
/// the bottom side reads correctly when the board is turned over).
pub fn text_strokes(text: &str, height: f64, mirror: bool) -> Vec<[Point; 2]> {
    let s = height / 6.0;
    let w = text_width(text, height);
    let mut out = vec![];
    for (i, ch) in text.chars().enumerate() {
        let ox = i as f64 * 6.0 * s - w / 2.0;
        for stroke in glyph(ch) {
            for pair in stroke.windows(2) {
                let map = |(x, y): (f32, f32)| {
                    let px = ox + x as f64 * s;
                    Point::new(if mirror { -px } else { px }, y as f64 * s - height / 2.0)
                };
                out.push([map(pair[0]), map(pair[1])]);
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn text_is_centred_and_sized() {
        let s = text_strokes("HH", 1.0, false);
        assert!(!s.is_empty());
        let (mut x0, mut x1, mut y0, mut y1) = (f64::MAX, f64::MIN, f64::MAX, f64::MIN);
        for seg in &s {
            for p in seg {
                x0 = x0.min(p.x);
                x1 = x1.max(p.x);
                y0 = y0.min(p.y);
                y1 = y1.max(p.y);
            }
        }
        assert!((y1 - y0 - 1.0).abs() < 1e-9, "height {}", y1 - y0);
        assert!((x1 - x0 - text_width("HH", 1.0)).abs() < 1e-9);
        assert!(((x0 + x1) / 2.0).abs() < 1e-9);
    }

    #[test]
    fn mirroring_flips_x_only() {
        let a = text_strokes("L", 2.0, false);
        let b = text_strokes("L", 2.0, true);
        assert_eq!(a.len(), b.len());
        for (s, m) in a.iter().zip(&b) {
            for k in 0..2 {
                assert!((s[k].x + m[k].x).abs() < 1e-12 && (s[k].y - m[k].y).abs() < 1e-12);
            }
        }
    }

    #[test]
    fn every_designator_character_has_a_glyph() {
        for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-+./_=()".chars() {
            assert!(!text_strokes(&c.to_string(), 1.0, false).is_empty(), "{c}");
        }
        assert!(text_strokes(" ", 1.0, false).is_empty());
        // unknown characters fall back to a visible '?'
        assert!(!text_strokes("あ", 1.0, false).is_empty());
        assert_eq!(text_strokes("r1", 1.0, false).len(), text_strokes("R1", 1.0, false).len());
    }
}

#!/usr/bin/env python3
"""Writes THIRD_PARTY_LICENSES.txt: every third-party crate the app is built from, its license,
and the license texts shipped inside the crates (identical texts are printed once).

    python tools/gen_third_party_licenses.py          # (re)generate the file
    python tools/gen_third_party_licenses.py --check  # exit 1 if the committed file is out of date

Run it again after changing a dependency (Cargo.lock). Needs only `cargo` and Python 3.
"""
import collections
import hashlib
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_LICENSES.txt"
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|COPYRIGHT|NOTICE|UNLICENSE)([-_. ].*)?$", re.I)


def metadata():
    r = subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
    if r.returncode != 0:
        sys.exit(r.stderr)
    return json.loads(r.stdout)


def third_party(md):
    members = set(md["workspace_members"])
    pk = {p["id"]: p for p in md["packages"]}
    nodes = {n["id"]: n for n in md["resolve"]["nodes"]}
    seen, stack = set(), list(members)
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if all(k["kind"] == "dev" for k in d["dep_kinds"]):
                continue  # test-only
            stack.append(d["pkg"])
    return sorted((pk[i] for i in seen if i not in members), key=lambda p: (p["name"], p["version"]))


def license_texts(pkg):
    """The license / notice files in the crate's source folder (top level only), as (file name, text)."""
    folder = pathlib.Path(pkg["manifest_path"]).parent
    found = []
    for f in sorted(folder.iterdir()):
        if f.is_file() and LICENSE_FILE.match(f.name):
            try:
                found.append((f.name, f.read_text(encoding="utf-8", errors="replace").strip()))
            except OSError:
                pass
    return found


def holder(pkg):
    """Copyright holder for a crate that ships no license file: the names in `authors` (e-mail addresses left out)."""
    names = [re.sub(r"\s*<[^>]*>", "", a).strip() for a in pkg.get("authors") or []]
    names = [n for n in names if n]
    return ", ".join(names) if names else f"the {pkg['name']} contributors"


def fallback_texts(pkg):
    """A crate without a license file in its package: the standard text of the license it names in Cargo.toml.
    MIT (or MIT OR ...) gets the MIT text with the crate's authors as copyright holders; Apache-2.0 gets the
    standard Apache text; any other license is only named (its SPDX page has the text)."""
    lic = pkg.get("license") or ""
    if re.search(r"(?<![A-Za-z-])MIT(?![A-Za-z-])", lic):
        body = (ROOT / "legacy-licenses" / "LICENSE-MIT").read_text(encoding="utf-8").strip().split("\n")
        body = [f"Copyright (c) {holder(pkg)}" if l.startswith("Copyright") else l for l in body]
        return [("MIT (standard text)", "\n".join(body))]
    if "Apache-2.0" in lic:
        return [("Apache-2.0 (standard text)", (ROOT / "legacy-licenses" / "LICENSE-APACHE").read_text(encoding="utf-8").strip())]
    ids = re.findall(r"[A-Za-z0-9.\-]+", lic)
    return [("license", f"{lic}\nStandard text: " + ", ".join(f"https://spdx.org/licenses/{i}.html" for i in ids if i not in ("OR", "AND", "WITH")))]


def build():
    md = metadata()
    pkgs = third_party(md)
    lines = []
    w = lines.append
    w("circuitCad - third-party licenses")
    w("=" * 72)
    w("circuitCad itself is available under AGPL-3.0-or-later (see LICENSE-AGPL; the versions up to v0.1.0-alpha.7 were published under MIT OR Apache-2.0, see legacy-licenses/).")
    w("It is built from the open-source crates listed below and bundles one font (BIZ UDGothic).")
    w("Where a crate offers a choice of licenses (\"A OR B\"), you may use it under either one.")
    w("Generated by tools/gen_third_party_licenses.py from Cargo.lock; do not edit by hand.")
    w("")
    w("Bundled font")
    w("-" * 72)
    w("BIZ UDGothic Regular (crates/app/assets/fonts/BIZUDGothic-Regular.ttf), SIL Open Font License 1.1.")
    w("The full license text is in crates/app/assets/fonts/OFL.txt and is reproduced at the end of this file.")
    w("")
    w(f"Rust crates ({len(pkgs)})")
    w("-" * 72)
    by_text = collections.OrderedDict()
    missing = []
    for p in pkgs:
        lic = p.get("license") or (f"see {p['license_file']}" if p.get("license_file") else "UNKNOWN")
        repo = p.get("repository") or p.get("homepage") or ""
        w(f"{p['name']} {p['version']} | {lic}" + (f" | {repo}" if repo else ""))
        texts = license_texts(p) or fallback_texts(p)
        if not license_texts(p):
            missing.append(f"{p['name']} {p['version']} ({lic})")
        for _, t in texts:
            h = hashlib.sha256(t.encode("utf-8")).hexdigest()
            by_text.setdefault(h, (t, []))[1].append(f"{p['name']} {p['version']}")
    w("")
    if missing:
        w("Crates whose package does not include a license file")
        w("-" * 72)
        w("For these, the standard text of the license named in their Cargo.toml is printed below, with the")
        w("crate's authors as the copyright holders (MIT) or the unmodified standard text (Apache-2.0).")
        for m in missing:
            w("  " + m)
        w("")
    w("License texts (each distinct text once, followed by the crates that ship it)")
    w("=" * 72)
    for n, (t, who) in enumerate(sorted(by_text.values(), key=lambda v: (-len(v[1]), v[0])), 1):
        w("")
        w(f"[{n}] used by: " + ", ".join(sorted(set(who))))
        w("-" * 72)
        w(t)
    w("")
    w("SIL Open Font License 1.1 (BIZ UDGothic)")
    w("=" * 72)
    w((ROOT / "crates/app/assets/fonts/OFL.txt").read_text(encoding="utf-8").strip())
    w("")
    return "\n".join(lines), len(pkgs), len(by_text), missing


def main():
    text, n, distinct, missing = build()
    if "--check" in sys.argv:
        old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if old.replace("\r\n", "\n") != text:
            sys.exit("THIRD_PARTY_LICENSES.txt is out of date: run `python tools/gen_third_party_licenses.py`")
        print("THIRD_PARTY_LICENSES.txt is up to date")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{n} crates, {distinct} distinct license texts, {len(text) // 1024} KB; {len(missing)} crates without a license file")
    for m in missing:
        print("  no license file:", m)


if __name__ == "__main__":
    main()
